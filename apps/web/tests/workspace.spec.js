import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test('owner login, chat reload, real planner, approved tool, settings and mobile navigation', async ({ page }) => {
  test.setTimeout(90000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const password = process.env.WORKSPACE_TEST_PASSWORD || (await readFile('.private/owner-password', 'utf8')).trim();
  await page.goto(process.env.WORKSPACE_TEST_URL || 'http://localhost:3000');
  await page.getByLabel('Password pemilik').fill(password);
  await page.getByRole('button', { name: 'Masuk ke workspace' }).click();
  await expect(page.getByText('Private owner workspace')).toBeVisible();
  await page.getByLabel('Provider AI').selectOption('demo');
  const prompt = 'Browser persistence ' + Date.now();
  await page.getByLabel('Pesan atau objective').fill(prompt);
  await page.getByRole('button', { name: 'Kirim', exact: true }).click();
  await expect(page.locator('.message-list')).toContainText('MODE DEMO', { timeout: 15000 });
  await page.reload();
  await page.getByRole('button', { name: prompt, exact: true }).click();
  await expect(page.locator('.message-list')).toContainText(prompt);
  await expect(page.locator('.message-list')).toContainText('MODE DEMO');
  await page.getByRole('button', { name: 'Agent tasks', exact: true }).click();
  await page.getByLabel('Pilih tool').selectOption('text.stats');
  await page.getByLabel('Pesan atau objective').fill('browser counts three');
  await page.getByRole('button', { name: 'Buat rencana' }).click();
  await expect(page.locator('.task-card')).toContainText('waiting_approval');
  await expect(page.getByRole('button', { name: 'Jalankan langkah berikutnya' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Setujui input & rencana' }).click();
  await page.getByRole('button', { name: 'Jalankan langkah berikutnya' }).click();
  await expect(page.locator('.task-card')).toContainText('succeeded');
  await expect(page.locator('.task-card')).toContainText('"words":3');
  // Check real AI planner separately from the deterministic manual tool slice.
  await page.getByLabel('Provider AI').selectOption('groq');
  await page.getByLabel('Pilih tool').selectOption('auto');
  await page.getByLabel('Pesan atau objective').fill('Use text.stats to count words in the exact text: one two three');
  await page.getByRole('button', { name: 'Buat rencana' }).click();
  await expect(page.locator('.task-card')).toContainText('waiting_approval', { timeout: 60000 });
  await expect(page.locator('.task-card')).toContainText('text.stats');
  await page.getByRole('button', { name: 'Tolak', exact: true }).click();
  await expect(page.locator('.task-card')).toContainText('cancelled');
  await page.getByRole('button', { name: 'Settings & integrations' }).click();
  await expect(page.getByRole('heading', { name: 'Integrations & limits' })).toBeVisible();
  await expect(page.locator('.integration-card').first()).toContainText('GROQ');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Buka navigasi' }).click();
  await expect(page.getByRole('button', { name: 'Keluar', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Keluar', exact: true }).click();
  await expect(page.getByLabel('Password pemilik')).toBeVisible();
  expect(errors).toEqual([]);
});
